def extract_advice_from_report(report_path: Path) -> Dict[int, Dict[str, str]]:
    """
    Extract LLM-generated advice text from coaching advice report.
    
    Args:
        report_path: Path to coaching advice report file
        
    Returns:
        Dictionary in format {turn: {'issue_name': 'advice_text'}}
    """
    if not report_path.exists():
        logger.warning(f"Report file not found: {report_path}")
        return {}
    
    content = report_path.read_text(encoding='utf-8')
    
    # Extract advice for each turn
    turn_advice = {}
    
    # Split by turn
    turn_sections = re.split(r'### Turn (\d+)', content)
    
    for i in range(1, len(turn_sections), 2):
        if i + 1 >= len(turn_sections):
            break
        
        turn_num = int(turn_sections[i])
        turn_content = turn_sections[i + 1]
        
        # Extract AI-Personalized Coaching Advice section
        if '**AI-Personalized Coaching Advice**' not in turn_content:
            continue
        
        advice_section = turn_content.split('**AI-Personalized Coaching Advice**')[1]
        
        # Extract advice for each issue
        issue_pattern = r'\*\*([^*]+?):\*\*\s*\n\s*\n(.*?)(?=\n\s*\*\*[^*]*?:|\n\s*---|\Z)'
        matches = re.finditer(issue_pattern, advice_section, re.DOTALL)
        
        turn_advice[turn_num] = {}
        for match in matches:
            issue_name = match.group(1).strip()
            
            # Skip "Actionable Recommendations", it's not an issue_name
            if issue_name.lower() in ['actionable recommendations', 'analysis']:
                continue
            
            advice_text = match.group(2).strip()
            
            # Clean text: remove excessive whitespace
            advice_text = re.sub(r'\n{3,}', '\n\n', advice_text)
            advice_text = advice_text.strip()
            
            if advice_text:
                turn_advice[turn_num][issue_name] = advice_text
    
    return turn_advice


def load_gold_references(gold_map_path: Path) -> Dict[int, Dict[str, List[str]]]:
    """
    Load reference texts from gold_map.jsonl.
    
    Args:
        gold_map_path: Path to gold_map.jsonl file
        
    Returns:
        Dictionary in format {turn: {'issue_name': [reference_texts]}}
    """
    if not gold_map_path.exists():
        logger.error(f"Gold map file not found: {gold_map_path}")
        return {}
    
    gold_refs = {}
    
    with open(gold_map_path, 'r', encoding='utf-8') as f:
        for line in f:
            if not line.strip():
                continue
            try:
                data = json.loads(line)
                # Handle case where turn may be None
                turn_value = data.get('turn')
                if turn_value is None:
                    continue  # Skip records with turn=None
                turn = int(turn_value)
                issue_name = data.get('issue_name', '')
                
                # Prefer gold_content (complete content), fallback to reference or gold_sections
                gold_content = data.get('gold_content', [])
                if not gold_content:
                    # Try reference field
                    reference = data.get('reference', '')
                    if reference:
                        gold_content = [reference]
                    else:
                        # Fallback to gold_sections (old format)
                        gold_sections = data.get('gold_sections', [])
                        gold_content = [' '.join(gold_sections)] if gold_sections else []
                
                if issue_name and gold_content:
                    if turn not in gold_refs:
                        gold_refs[turn] = {}
                    if issue_name not in gold_refs[turn]:
                        gold_refs[turn][issue_name] = []
                    
                    # Merge gold_content into reference text
                    reference_text = '\n\n'.join(gold_content) if isinstance(gold_content, list) else gold_content
                    gold_refs[turn][issue_name].append(reference_text)
            except json.JSONDecodeError as e:
                logger.warning(f"Failed to parse line in gold_map: {e}")
                continue
            except (ValueError, KeyError) as e:
                logger.warning(f"Failed to process line in gold_map: {e}")
                continue
    
    return gold_refs


def evaluate_advice(
    generated_advice: Dict[int, Dict[str, str]],
    gold_references: Dict[int, Dict[str, List[str]]]
) -> pd.DataFrame:
    """
    Evaluate quality of generated advice.
    
    Args:
        generated_advice: Generated advice in format {turn: {'issue_name': 'advice_text'}}
        gold_references: Reference texts in format {turn: {'issue_name': [reference_texts]}}
        
    Returns:
        DataFrame containing evaluation results
    """
    results = []
    
    # Collect all (turn, issue_name) pairs to evaluate
    all_pairs = set()
    for turn, issues in generated_advice.items():
        for issue_name in issues.keys():
            all_pairs.add((turn, issue_name))
    
    for turn, issue_name in all_pairs:
        generated_text = generated_advice.get(turn, {}).get(issue_name, '')
        reference_list = gold_references.get(turn, {}).get(issue_name, [])
        
        if not generated_text:
            logger.warning(f"No generated text for Turn {turn}, Issue: {issue_name}")
            continue
        
        if not reference_list:
            logger.warning(f"No reference text for Turn {turn}, Issue: {issue_name}")
            continue
        
        # Use first reference text (if multiple available)
        reference_text = reference_list[0] if reference_list else ''
        
        if not reference_text:
            continue
        
        # Compute BERTScore
        bertscore_f1 = None
        if BERTSCORE_AVAILABLE:
            try:
                P, R, F1 = bert_score(
                    [generated_text],
                    [reference_text],
                    lang='en',
                    verbose=False
                )
                bertscore_f1 = float(F1[0].item())
            except Exception as e:
                logger.warning(f"BERTScore calculation failed: {e}")
        
        # Compute NLI (Natural Language Inference)
        nli_entailment = None
        nli_contradiction = None
        nli_neutral = None
        
        if NLI_AVAILABLE:
            try:
                # Lazy initialization of NLI model (load only on first use)
                global nli_model, nli_tokenizer
                if nli_model is None:
                    logger.info("Loading NLI model (this may take a moment, ~1.3GB download)...")
                    try:
                        model_name = "roberta-large-mnli"
                        nli_tokenizer = AutoTokenizer.from_pretrained(model_name)
                        nli_model = AutoModelForSequenceClassification.from_pretrained(model_name)
                        nli_model.eval()  # Set to evaluation mode
                        device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
                        nli_model.to(device)
                        logger.info(f"NLI model loaded successfully on {device}")
                    except Exception as e:
                        logger.error(f"Failed to load NLI model: {e}")
                        nli_model = False  # Mark as failed to avoid repeated attempts
                
                if nli_model is False:
                    # Model loading failed, skip NLI evaluation
                    pass
                else:
                    # NLI evaluation: determine if generated text entails reference text (logical consistency)
                    # Format: premise: reference_text, hypothesis: generated_text
                    # We evaluate in both directions:
                    # 1. reference -> generated (whether generated text is logically consistent with reference)
                    # 2. generated -> reference (whether reference text is logically consistent with generated)
                    
                    # Truncate text if too long (NLI models typically have length limits)
                    max_length = 512
                    ref_truncated = reference_text[:max_length] if len(reference_text) > max_length else reference_text
                    gen_truncated = generated_text[:max_length] if len(generated_text) > max_length else generated_text
                    
                    try:
                        device = next(nli_model.parameters()).device
                        
                        # Evaluate reference -> generated (premise: reference, hypothesis: generated)
                        inputs1 = nli_tokenizer(ref_truncated, gen_truncated, 
                                               return_tensors="pt", 
                                               truncation=True, 
                                               max_length=512,
                                               padding=True)
                        inputs1 = {k: v.to(device) for k, v in inputs1.items()}
                        
                        with torch.no_grad():
                            outputs1 = nli_model(**inputs1)
                            logits1 = outputs1.logits
                            probs1 = torch.nn.functional.softmax(logits1, dim=-1)
                        
                        # Evaluate generated -> reference (premise: generated, hypothesis: reference)
                        inputs2 = nli_tokenizer(gen_truncated, ref_truncated,
                                               return_tensors="pt",
                                               truncation=True,
                                               max_length=512,
                                               padding=True)
                        inputs2 = {k: v.to(device) for k, v in inputs2.items()}
                        
                        with torch.no_grad():
                            outputs2 = nli_model(**inputs2)
                            logits2 = outputs2.logits
                            probs2 = torch.nn.functional.softmax(logits2, dim=-1)
                        
                        # MNLI label order: 0=contradiction, 1=neutral, 2=entailment
                        # Average scores from both directions
                        entailment1 = float(probs1[0][2].item())  # entailment
                        entailment2 = float(probs2[0][2].item())
                        nli_entailment = (entailment1 + entailment2) / 2.0
                        
                        contradiction1 = float(probs1[0][0].item())  # contradiction
                        contradiction2 = float(probs2[0][0].item())
                        nli_contradiction = (contradiction1 + contradiction2) / 2.0
                        
                        neutral1 = float(probs1[0][1].item())  # neutral
                        neutral2 = float(probs2[0][1].item())
                        nli_neutral = (neutral1 + neutral2) / 2.0
                        
                    except Exception as e:
                        logger.warning(f"NLI inference failed: {e}")
                
            except Exception as e:
                logger.warning(f"NLI calculation failed: {e}")
        
        results.append({
            'turn': turn,
            'issue_name': issue_name,
            'bertscore_f1': bertscore_f1,
            'nli_entailment': nli_entailment,
            'nli_contradiction': nli_contradiction,
            'nli_neutral': nli_neutral,
            'generated_length': len(generated_text),
            'reference_length': len(reference_text)
        })
    
    return pd.DataFrame(results)


def main():
    """Main function"""
    # Set paths
    # Note: This script assumes it's in Github/Eval directory
    # Adjust paths according to your project structure
    script_dir = Path(__file__).parent
    github_dir = script_dir.parent  # Github folder
    project_root = github_dir.parent  # Project root (if Github is inside project)
    eval_dir = script_dir
    
    # Gold map path - adjust this path according to your setup
    # Option 1: If gold_map is in project root's eval folder
    gold_map_path = project_root / 'eval' / 'gold_map_extended.jsonl'
    # Option 2: If gold_map is in a different location, uncomment and modify:
    # gold_map_path = Path('path/to/your/gold_map_extended.jsonl')
    
    if not gold_map_path.exists():
        logger.warning(f"Gold map not found at {gold_map_path}")
        logger.warning("Please update the gold_map_path in the script to point to your gold_map_extended.jsonl file")
        return 1
    
    # Model directory mapping
    # NOTE: These paths are examples. Update them to point to your actual model output directories.
    # Each model directory should contain a 'coaching_advice_report.md' file
    model_dirs = {
        'GPT-4o': github_dir / 'models' / 'gpt4o',  # Example: adjust to your structure
        'GPT-4-Turbo': github_dir / 'models' / 'gpt4turbo',
        'GPT-5.1': github_dir / 'models' / 'gpt5.1',
        'Claude-Opus-4.5': github_dir / 'models' / 'opus4.5',
        'Gemini-3-Pro': github_dir / 'models' / 'gemini3pro',
        'DeepSeek-V3.2': github_dir / 'models' / 'deepseek3.2'
    }
    
    # Alternative: If models are in a different location, you can use absolute paths:
    # model_dirs = {
    #     'GPT-4o': Path('/path/to/your/models/gpt4o'),
    #     ...
    # }
    
    # Create output directory
    eval_dir.mkdir(exist_ok=True)
    
    # Load gold references
    logger.info(f"Loading gold references from: {gold_map_path}")
    gold_references = load_gold_references(gold_map_path)
    logger.info(f"Loaded {len(gold_references)} turns from gold map")
    
    # Evaluate each model
    all_results = []
    
    for model_name, model_dir in model_dirs.items():
        report_path = model_dir / 'coaching_advice_report.md'
        
        if not report_path.exists():
            logger.warning(f"Report not found for {model_name}: {report_path}")
            continue
        
        logger.info(f"\n{'='*70}")
        logger.info(f"Evaluating: {model_name}")
        logger.info(f"{'='*70}")
        
        # Extract generated advice
        generated_advice = extract_advice_from_report(report_path)
        logger.info(f"Extracted advice for {len(generated_advice)} turns")
        
        # Evaluate
        df = evaluate_advice(generated_advice, gold_references)
        
        if df.empty:
            logger.warning(f"No evaluation results for {model_name}")
            continue
        
        # Add model name
        df['model'] = model_name
        
        # Save individual model results
        output_csv = eval_dir / f'eval_{model_name.lower().replace("-", "_").replace(" ", "_")}.csv'
        df.to_csv(output_csv, index=False, encoding='utf-8')
        logger.info(f"Saved results to: {output_csv}")
        
        # Calculate average metrics
        metrics = {
            'model': model_name,
            'bertscore_f1': float(df['bertscore_f1'].mean()) if df['bertscore_f1'].notna().any() else None,
            'nli_entailment': float(df['nli_entailment'].mean()) if df['nli_entailment'].notna().any() else None,
            'nli_contradiction': float(df['nli_contradiction'].mean()) if df['nli_contradiction'].notna().any() else None,
            'nli_neutral': float(df['nli_neutral'].mean()) if df['nli_neutral'].notna().any() else None,
            'generated_length': float(df['generated_length'].mean()),
            'reference_length': float(df['reference_length'].mean()),
            'num_samples': len(df)
        }
        
        logger.info(f"Average metrics for {model_name}:")
        if metrics['bertscore_f1'] is not None:
            logger.info(f"  BERTScore F1: {metrics['bertscore_f1']:.4f}")
        if metrics['nli_entailment'] is not None:
            logger.info(f"  NLI Entailment: {metrics['nli_entailment']:.4f}")
        if metrics['nli_contradiction'] is not None:
            logger.info(f"  NLI Contradiction: {metrics['nli_contradiction']:.4f}")
        if metrics['nli_neutral'] is not None:
            logger.info(f"  NLI Neutral: {metrics['nli_neutral']:.4f}")
        logger.info(f"  Generated length: {metrics['generated_length']:.1f} chars")
        logger.info(f"  Reference length: {metrics['reference_length']:.1f} chars")
        logger.info(f"  Number of samples: {metrics['num_samples']}")
        
        all_results.append(df)
    
    # Combine all results
    if all_results:
        combined_df = pd.concat(all_results, ignore_index=True)
        combined_csv = eval_dir / 'eval_all_models.csv'
        combined_df.to_csv(combined_csv, index=False, encoding='utf-8')
        logger.info(f"\nSaved combined results to: {combined_csv}")
        
        # Generate summary report
        summary_data = []
        for model_name, model_dir in model_dirs.items():
            model_df = combined_df[combined_df['model'] == model_name]
            if not model_df.empty:
                summary_data.append({
                    'Model': model_name,
                    'BERTScore F1': f"{model_df['bertscore_f1'].mean():.4f}" if model_df['bertscore_f1'].notna().any() else 'N/A',
                    'NLI Entailment': f"{model_df['nli_entailment'].mean():.4f}" if model_df['nli_entailment'].notna().any() else 'N/A',
                    'NLI Contradiction': f"{model_df['nli_contradiction'].mean():.4f}" if model_df['nli_contradiction'].notna().any() else 'N/A',
                    'Avg Generated Length': f"{model_df['generated_length'].mean():.1f}",
                    'Num Samples': len(model_df)
                })
        
        summary_df = pd.DataFrame(summary_data)
        summary_csv = eval_dir / 'eval_summary.csv'
        summary_df.to_csv(summary_csv, index=False, encoding='utf-8')
        logger.info(f"Saved summary to: {summary_csv}")
        
        # Print summary table
        print("\n" + "="*70)
        print("Evaluation Summary")
        print("="*70)
        print(summary_df.to_string(index=False))
        print("="*70)
        
        # Generate Markdown report
        markdown_lines = [
            "# Model Evaluation Summary\n\n",
            "## Metrics Comparison\n\n"
        ]
        
        # Generate Markdown table
        try:
            markdown_lines.append(summary_df.to_markdown(index=False))
        except AttributeError:
            # If to_markdown method not available, generate table manually
            headers = summary_df.columns.tolist()
            markdown_lines.append("| " + " | ".join(headers) + " |")
            markdown_lines.append("| " + " | ".join(["---"] * len(headers)) + " |")
            for _, row in summary_df.iterrows():
                markdown_lines.append("| " + " | ".join(str(val) for val in row) + " |")
        
        markdown_lines.extend([
            "\n\n## Detailed Results\n\n",
            "Individual model results are saved in separate CSV files:\n\n"
        ])
        
        for model_name in model_dirs.keys():
            safe_name = model_name.lower().replace("-", "_").replace(" ", "_")
            markdown_lines.append(f"- `eval_{safe_name}.csv` - {model_name} detailed results\n")
        
        markdown_lines.extend([
            "\n## Combined Results\n\n",
            f"All results combined: `eval_all_models.csv`\n\n",
            "## Gold Map\n\n",
            f"Using gold map: `{gold_map_path.relative_to(project_root)}`\n"
        ])
        
        summary_md = eval_dir / 'eval_summary.md'
        summary_md.write_text(''.join(markdown_lines), encoding='utf-8')
        logger.info(f"Saved Markdown summary to: {summary_md}")
    
    logger.info("\nEvaluation completed!")


if __name__ == '__main__':
    main()
